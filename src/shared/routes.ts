/**
 * 라우트 경로의 단일 소스.
 *
 * 화면에서 `href="/spots/abc"`처럼 문자열을 직접 쓰면, 경로가 바뀔 때
 * grep으로만 찾을 수 있는 링크가 남는다. 여기 함수를 거치면 시그니처가 바뀌는
 * 순간 타입 검사가 호출부를 전부 짚어 준다.
 *
 * 이 모듈은 shared(최하단)라 아무것도 import하지 않는다 — 경로 조립은 순수
 * 문자열 연산이므로 그럴 필요도 없다.
 */

export const HOME_PATH = '/';

/**
 * 업로드 화면. 메인 플로우의 STEP 1이다.
 *
 * 초기 화면(`/`)에 두지 않는다. 저장이 끝나면 지도로 넘어가고 지도를 닫으면
 * 초기 화면으로 돌아오는데, 그 자리를 무엇으로 둘지는 아직 정해지지 않았다 —
 * 경로를 따로 두면 그 결정과 무관하게 이 화면이 존재할 수 있다.
 */
export const UPLOAD_PATH = '/upload';

/**
 * 추출 결과를 검토하는 독립 페이지. 메인 플로우의 STEP 3이다.
 *
 * 여러 건을 확인하고 실패 건의 주소까지 고치는 긴 작업이라 업로드 화면의
 * 모달이나 바텀시트에 얹지 않는다(D03). T12가 추출 결과를 넘기는 연결은 이
 * 경로를 목적지로 삼는다.
 */
export const UPLOAD_RESULTS_PATH = '/upload/results';

/**
 * 동선 만들기 화면(M7). 한 문장을 받아 저장된 스팟으로 여정을 제안한다.
 *
 * 지도(`/`)와 갈라 둔 이유는 진입 의도가 다르기 때문이다 — 지도는 "무엇을
 * 저장했나"를 보고, 여기는 "오늘 어디를 갈까"를 묻는다. 한 화면에 두면 둘 중
 * 하나는 스크롤 아래로 밀린다.
 */
export const ROUTE_PATH = '/route';

/**
 * URL 세그먼트로 안전한 형태인지 검사한다.
 *
 * slug를 그대로 경로에 붙이면 `..`이나 `/`가 섞였을 때 다른 경로로 튄다.
 * 만드는 쪽에서 한 번 막아 두는 편이, 받는 쪽마다 방어하는 것보다 싸다.
 */
export function isValidSlug(slug: string): boolean {
  return /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug);
}
